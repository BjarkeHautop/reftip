#' Add two numbers
#'
#' Adds `a` and `b` together and returns the sum.
#'
#' @param a A number.
#' @param b A number.
#'
#' @return A number.
#' @export
#'
#' @examples
#' foo(1, 2)
foo <- function(a, b) {
  a + b
}

#' Multiply two numbers
#'
#' Multiplies `a` and `b` together.
#'
#' @param a A number.
#' @param b A number.
#'
#' @return A number.
#' @export
bar <- function(a, b) {
  a * b
}
